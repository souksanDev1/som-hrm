/** Translate a key; unknown keys (e.g. server error codes) fall back to `error.<key>` then the key itself. */
export const translate = (locale: Locale, key: string): string => {
  const dict = dictionaries[locale];
  return (dict as Record<string, string>)[key] ?? (dict as Record<string, string>)[`error.${key}`] ?? key;
};
